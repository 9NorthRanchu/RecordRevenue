-- Mapcode — GPS ของรถเช่าในญี่ปุ่นรับตัวเลขชุดนี้ได้ตรง ๆ
-- ค้นด้วยชื่อสถานที่ในเครื่อง GPS มักไม่เจอ (ระบบเป็นภาษาญี่ปุ่น) แต่ mapcode เข้าได้เสมอ
-- เก็บเป็นข้อความ ไม่ใช่ตัวเลข เพราะมีจุดคั่นและเลขนำหน้าศูนย์ เช่น '149 287 165*36'
ALTER TABLE TripStops ADD COLUMN mapcode TEXT;

-- เวลาเปิด-ปิด เก็บแยกเป็น HH:MM เพื่อ "เทียบกับเวลาที่วางแผนไว้ได้"
-- ถ้าเก็บเป็นข้อความอิสระจะเตือนอัตโนมัติไม่ได้ ได้แค่โชว์เฉย ๆ
ALTER TABLE TripStops ADD COLUMN open_time TEXT;
ALTER TABLE TripStops ADD COLUMN close_time TEXT;

-- วันหยุดประจำสัปดาห์ — เก็บเป็นเลขวันคั่นด้วยจุลภาค ตาม Date.getDay() ของ JS
-- 0 = อาทิตย์ … 6 = เสาร์ · เช่น '3' = หยุดพุธ · '' หรือ NULL = เปิดทุกวัน
